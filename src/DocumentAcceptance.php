/** Publishes TAP, TEP and TA PDFs and records an auditable customer acceptance. */
class DocumentAcceptance extends CommonDBTM
{
   protected static $notable = true;

   public static function getTable($classname = null): string { return 'glpi_plugin_projectplus_documentacceptances'; }

   /** @return array<string,string> */
   private static function typesForItem(CommonDBTM $item): array
   {
      if ($item instanceof Ticket) { return ['tap' => __('TAP - Termo de Abertura do Projeto', 'projectplus')]; }
      if ($item instanceof Project) { return ['tep' => __('TEP - Relatório de Entrega do Projeto', 'projectplus'), 'ta' => __('TA - Termo de Aceite', 'projectplus')]; }
      return [];
   }

   public function getTabNameForItem(CommonGLPI $item, $withtemplate = 0): string
   {
      if ($withtemplate || !($item instanceof Ticket || $item instanceof Project)) { return ''; }
      if ($item instanceof Ticket && !TicketConfig::isEnabledForTicket($item)) { return ''; }
      return self::createTabEntry(__('Project+', 'projectplus'), 0, $item::getType(), 'ti ti-file-check');
   }

   public static function displayTabContentForItem(CommonGLPI $item, $tabnum = 1, $withtemplate = 0): bool
   {
      if ($item instanceof Ticket || $item instanceof Project) { self::showForItem($item); }
      return true;
   }

   /** @return array<string,mixed>|null */
   public static function getForItem(CommonDBTM $item, string $type): ?array
   {
      /** @var DBmysql $DB */ global $DB;
      $row = $DB->request(['FROM'=>self::getTable(),'WHERE'=>['itemtype'=>$item::getType(),'items_id'=>(int)$item->getID(),'document_type'=>$type],'LIMIT'=>1])->current();
      return $row ?: null;
   }

   /** @param array<string,mixed>|null $row */
   public static function getVisualState(?array $row): string
   {
      if ($row === null) { return 'disabled'; }
      if ((string) $row['status'] === 'accepted') { return 'accepted'; }
      if ((string) $row['status'] === 'rejected') { return 'rejected'; }
      return 'released';
   }

   public static function canManageDocument(CommonDBTM $item, string $type, string $action = 'fill'): bool
   {
      if (!array_key_exists($type, self::typesForItem($item))) {
         return false;
      }
      // Project+ actions are governed by the plugin profile matrix. Native
      // Ticket/Project update rights must not become an additional gate here.
      return ProjectProfile::haveDocumentActionRight($type, $action);
   }

   /** Determines whether a Project+ user may view a document generated by the plugin. */
   public static function canViewDocument(CommonDBTM $item, string $type): bool
   {
      if (!array_key_exists($type, self::typesForItem($item))) {
         return false;
      }

      // "Ler" is an explicit Project+ permission in the profile matrix.
      // A requester with only this right must be able to open the generated
      // document, even when they are not allowed to fill, generate or send it.
      if (Session::haveRight(ProjectProfile::getDocumentManagementRight($type), READ)) {
         return true;
      }

      foreach (['fill', 'generate', 'send', 'accept'] as $action) {
         // Action columns in the Project+ profile matrix are persisted as
         // UPDATE rights. Possessing one of them also grants document view.
         if (ProjectProfile::haveDocumentActionRight($type, $action, UPDATE)) {
            return true;
         }
      }
      return self::canAccept($item, $type);
   }

   private static function canAccept(CommonDBTM $item, string $type = ''): bool
   {
      $userId = (int) Session::getLoginUserID();
      if ($userId <= 0) { return false; }
      if ($type !== '' && !ProjectProfile::haveDocumentActionRight($type, 'accept', UPDATE)) {
         return false;
      }
      /** @var DBmysql $DB */ global $DB;
      if ($item instanceof Ticket) {
         return (int)($DB->request(['COUNT'=>'count','FROM'=>Ticket_User::getTable(),'WHERE'=>['tickets_id'=>(int)$item->getID(),'users_id'=>$userId,'type'=>CommonITILActor::REQUESTER]])->current()['count'] ?? 0) > 0;
      }
      if ($item instanceof Project) {
         $data = ProjectData::getForProject((int)$item->getID());
         return in_array($userId, [(int)$data['requester_users_id'], (int)$data['focal_point_users_id']], true);
      }
      return false;
   }

   public static function publish(CommonDBTM $item, string $type, int $templateId): void
   {
      if (!self::canManageDocument($item, $type, 'send')) { throw new \RuntimeException(__('Sem permissão para publicar este documento.', 'projectplus')); }
      if ($item instanceof Project && $type === 'ta') {
         $tep = self::getForItem($item, 'tep');
         if (!$tep || (string) $tep['status'] !== 'accepted') {
            throw new \RuntimeException(__('O TA só pode ser publicado após o aceite do TEP.', 'projectplus'));
         }
      }
      $templates = DocumentTemplate::get((int)$item->getEntityID(), $templateId);
      $template = $templates[0] ?? null;
      if (!$template || (string)$template['document_type'] !== $type || !(int)$template['is_active']) { throw new \RuntimeException(__('Selecione um modelo ativo compatível.', 'projectplus')); }
      $documentId = (int)$template['documents_id'];
      $document = new Document();
      if ($documentId <= 0 || !$document->getFromDB($documentId)) { throw new \RuntimeException(__('Selecione um documento válido.', 'projectplus')); }
      /** @var DBmysql $DB */ global $DB;
      $now = date('Y-m-d H:i:s'); $current = self::getForItem($item, $type);
      $data = ['documents_id'=>$documentId,'status'=>'published','published_users_id'=>(int)Session::getLoginUserID(),'accepted_users_id'=>0,'rejected_users_id'=>0,'rejection_justification'=>null,'date_rejected'=>null,'date_published'=>$now,'date_accepted'=>null,'date_mod'=>$now];
      if ($current) { $DB->update(self::getTable(),$data,['id'=>(int)$current['id']]); }
      else { $DB->insert(self::getTable(),$data+['itemtype'=>$item::getType(),'items_id'=>(int)$item->getID(),'entities_id'=>(int)$item->getEntityID(),'document_type'=>$type]); }
      if ($item instanceof Ticket && $type === 'tap') { TicketPhase::setPhase($item, 'awaiting_tap_acceptance', __('TAP publicado para aceite.', 'projectplus')); }
   }

   public static function publishGenerated(CommonDBTM $item, string $type): void
   {
      if (!self::canManageDocument($item, $type, 'send')) throw new \RuntimeException(__('Sem permissão para enviar este documento.', 'projectplus'));
      $draft = DocumentDraft::get($item::getType(), (int)$item->getID(), $type);
      if (!$draft || (string)$draft['status'] !== 'generated') throw new \RuntimeException(__('Gere o documento antes de enviá-lo para aceite.', 'projectplus'));
      global $DB; $now=date('Y-m-d H:i:s'); $current=self::getForItem($item,$type);
      $data=['documents_id'=>0,'status'=>'published','published_users_id'=>(int)Session::getLoginUserID(),'accepted_users_id'=>0,'rejected_users_id'=>0,'rejection_justification'=>null,'date_rejected'=>null,'date_published'=>$now,'date_accepted'=>null,'date_mod'=>$now];
      if($current)$DB->update(self::getTable(),$data,['id'=>(int)$current['id']]);else $DB->insert(self::getTable(),$data+['itemtype'=>$item::getType(),'items_id'=>(int)$item->getID(),'entities_id'=>(int)$item->getEntityID(),'document_type'=>$type]);
      self::addFollowup($item, $type, __('Documento gerado enviado para aceite.', 'projectplus'));
      if($item instanceof Ticket&&$type==='tap')TicketPhase::setPhase($item,'awaiting_tap_acceptance',__('TAP enviado para aceite.','projectplus'));
   }

   public static function accept(CommonDBTM $item, int $acceptanceId): void
   {
      /** @var DBmysql $DB */ global $DB;
      $row = $DB->request(['FROM'=>self::getTable(),'WHERE'=>['id'=>$acceptanceId,'itemtype'=>$item::getType(),'items_id'=>(int)$item->getID(),'status'=>'published'],'LIMIT'=>1])->current();
      if (!$row || !self::canAccept($item, (string) $row['document_type'])) { throw new \RuntimeException(__('Você não possui permissão para aceitar este documento.', 'projectplus')); }
      $now = date('Y-m-d H:i:s');
      $DB->update(self::getTable(),['status'=>'accepted','accepted_users_id'=>(int)Session::getLoginUserID(),'date_accepted'=>$now,'date_mod'=>$now],['id'=>(int)$row['id']]);
      self::addFollowup($item, (string)$row['document_type'], __('Aceite do documento registrado.', 'projectplus'));
      if ($item instanceof Ticket && (string)$row['document_type'] === 'tap') { TicketPhase::setPhase($item, 'authorized_opening', __('TAP aceito pelo cliente.', 'projectplus')); }
      if ($item instanceof Project && (string) $row['document_type'] === 'ta') {
         $projectUpdate = ['id' => (int) $item->getID(), 'percent_done' => 100, 'real_end_date' => $now];
         $finishedStateId = self::getFinishedProjectStateId();
         if ($finishedStateId > 0) {
            $projectUpdate['projectstates_id'] = $finishedStateId;
         }
         $item->update($projectUpdate);
      }
   }

   /** Refuses a published TAP, TEP or TA and returns it to the manager for correction. */
   public static function reject(CommonDBTM $item, int $acceptanceId, string $justification): void
   {
      $justification = trim($justification);
      if ($justification === '') {
         throw new \RuntimeException(__('Informe a justificativa da recusa.', 'projectplus'));
      }
      /** @var DBmysql $DB */ global $DB;
      $row = $DB->request([
         'FROM' => self::getTable(),
         'WHERE' => [
            'id' => $acceptanceId,
            'itemtype' => $item::getType(),
            'items_id' => (int) $item->getID(),
            'status' => 'published',
         ],
         'LIMIT' => 1,
      ])->current();
      if (!$row || !self::canAccept($item, (string) $row['document_type'])) {
         throw new \RuntimeException(__('Você não possui permissão para recusar este documento.', 'projectplus'));
      }
      $now = date('Y-m-d H:i:s');
      $DB->update(self::getTable(), [
         'status' => 'rejected',
         'rejected_users_id' => (int) Session::getLoginUserID(),
         'rejection_justification' => $justification,
         'date_rejected' => $now,
         'date_mod' => $now,
      ], ['id' => (int) $row['id']]);
      self::addFollowup(
         $item,
         (string) $row['document_type'],
         sprintf(__('Documento recusado pelo cliente. Justificativa: %s', 'projectplus'), $justification)
      );
   }

   /** Returns the native GLPI project state marked as finished, if configured. */
   private static function getFinishedProjectStateId(): int
   {
      /** @var DBmysql $DB */ global $DB;
      $state = $DB->request([
         'FROM'  => ProjectState::getTable(),
         // ProjectState in GLPI 10 does not have an is_deleted column.
         // The is_finished flag is the native source of truth for closure.
         'WHERE' => ['is_finished' => 1],
         'ORDER' => ['id ASC'],
         'LIMIT' => 1,
      ])->current();
      return $state ? (int) $state['id'] : 0;
   }

   /** @return array<string,mixed>|null */
   public static function getViewableAcceptance(CommonDBTM $item, int $acceptanceId): ?array
   {
      /** @var DBmysql $DB */ global $DB;
      $row = $DB->request(['FROM'=>self::getTable(),'WHERE'=>['id'=>$acceptanceId,'itemtype'=>$item::getType(),'items_id'=>(int)$item->getID()],'LIMIT'=>1])->current();
      if (!$row || (!self::canManageDocument($item, (string) $row['document_type']) && !self::canAccept($item, (string) $row['document_type']))) { return null; }
      return $row;
   }

   public static function showForItem(CommonDBTM $item): void
   {
      if ($item instanceof Project) {
         self::showProjectJourney($item);
         return;
      }

      $types = self::typesForItem($item);
      echo "<div class='projectplus-tip projectplus-acceptance'><header class='projectplus-tip__hero'><div class='projectplus-tip__hero-icon'><i class='ti ti-file-check'></i></div><div><span class='projectplus-tip__eyebrow'>" . self::esc(__('Validação documental', 'projectplus')) . '</span><h2>' . self::esc(__('Project+', 'projectplus')) . '</h2><p>' . self::esc(__('Leia o documento publicado e registre seu aceite de forma auditável.', 'projectplus')) . '</p></div></header>';
      foreach ($types as $type => $label) { self::showDocument($item, $type, $label); }
      echo '</div>';
   }

   /** Renders the TAP step inside the unified Ticket documents journey. */
   public static function showTicketDocument(Ticket $ticket): void
   {
      $phase = TicketPhase::getForTicket((int) $ticket->getID());
      $row = self::getForItem($ticket, 'tap');
      $allowedPhases = ['authorized_opening', 'awaiting_tap_acceptance', 'project_opened'];
      if (!$row && !in_array((string) ($phase['phase'] ?? ''), $allowedPhases, true)) {
         echo "<div class='alert alert-info'>" . self::esc(__('O TAP será liberado após a autorização de abertura do projeto.', 'projectplus')) . '</div>';
         return;
      }
      self::showDocument($ticket, 'tap', __('TAP - Termo de Abertura do Projeto', 'projectplus'));
   }

   /**
    * Presents the complete documentary sequence in a project, using the
    * linked ticket as the source for TIP and TAP.
    */
   private static function showProjectJourney(Project $project): void
   {
      $ticketId = TicketProject::getTicketIdForProject((int) $project->getID());
      echo "<div class='projectplus-tip projectplus-acceptance'><header class='projectplus-tip__hero'><div class='projectplus-tip__hero-icon'><i class='ti ti-file-check'></i></div><div><span class='projectplus-tip__eyebrow'>" . self::esc(__('Jornada documental', 'projectplus')) . '</span><h2>' . self::esc(__('Termos', 'projectplus')) . '</h2><p>' . self::esc(__('Acompanhe os documentos do projeto na ordem do fluxo.', 'projectplus')) . '</p></div></header>';
      self::showDocumentLegend();
      echo '<div class="projectplus-document-journey">';

      $ticket = new Ticket();
      $hasTicket = $ticketId > 0 && $ticket->getFromDB($ticketId);
       $preTip = $hasTicket ? TicketIntent::getForTicket((int) $ticket->getID(), 'pretip') : null;
       $preTipState = (string) ($preTip['status'] ?? '') === 'accepted' ? 'accepted' : ((string) ($preTip['status'] ?? '') === 'rejected' ? 'rejected' : ($preTip ? 'released' : 'disabled'));
       $intent = $hasTicket ? TicketIntent::getForTicket((int) $ticket->getID(), 'tip') : null;
      $tipState = (string) ($intent['status'] ?? '') === 'accepted' ? 'accepted' : ((string) ($intent['status'] ?? '') === 'rejected' ? 'rejected' : ($intent ? 'released' : 'disabled'));
      $tapState = $hasTicket ? self::getVisualState(self::getForItem($ticket, 'tap')) : 'disabled';
      $tepState = self::getVisualState(self::getForItem($project, 'tep'));
      if ($tepState === 'disabled') {
         $tepState = 'released';
      }
      $taState = self::getVisualState(self::getForItem($project, 'ta'));
      if ($taState === 'disabled' && $tepState === 'accepted') {
         $taState = 'released';
      }
       self::showJourneyStep(__('TIP - Termo de Intenção de Projeto', 'projectplus'), 'ti ti-file-search', $preTipState, false, static function () use ($hasTicket, $ticket): void {
          if ($hasTicket) { TicketIntent::showForTicket($ticket, 'pretip'); }
          else { echo "<div class='alert alert-info'>" . self::esc(__('Não há chamado de origem vinculado a este projeto.', 'projectplus')) . '</div>'; }
       });
       self::showJourneyStep(__('TIP - Detalhamento Técnico', 'projectplus'), 'ti ti-file-text', $tipState, false, static function () use ($hasTicket, $ticket): void {
         if ($hasTicket) { TicketIntent::showForTicket($ticket); }
         else { echo "<div class='alert alert-info'>" . self::esc(__('Não há chamado de origem vinculado a este projeto.', 'projectplus')) . '</div>'; }
      });
      self::showJourneyStep(__('TAP - Termo de Abertura do Projeto', 'projectplus'), 'ti ti-file-description', $tapState, false, static function () use ($hasTicket, $ticket): void {
         if ($hasTicket) { self::showDocument($ticket, 'tap', __('TAP - Termo de Abertura do Projeto', 'projectplus')); }
         else { echo "<div class='alert alert-info'>" . self::esc(__('Documento indisponível.', 'projectplus')) . '</div>'; }
      });
      self::showJourneyStep(__('TEP - Relatório de Entrega do Projeto', 'projectplus'), 'ti ti-report', $tepState, false, static function () use ($project): void {
         self::showDocument($project, 'tep', __('TEP - Relatório de Entrega do Projeto', 'projectplus'));
      });
      self::showJourneyStep(__('TA - Termo de Aceite', 'projectplus'), 'ti ti-file-certificate', $taState, false, static function () use ($project): void {
         self::showDocument($project, 'ta', __('TA - Termo de Aceite', 'projectplus'));
      });
      echo '</div></div>';
      self::showJourneyAccordionScript();
   }

   /** Ensures a document journey behaves as a one-at-a-time accordion. */
   public static function showJourneyAccordionScript(): void
   {
      echo "<script>(function () { document.querySelectorAll('.projectplus-document-journey').forEach(function (journey) { if (journey.dataset.projectplusAccordionReady) { return; } journey.dataset.projectplusAccordionReady = '1'; journey.querySelectorAll('.projectplus-document-step').forEach(function (step) { step.addEventListener('toggle', function () { if (!step.open) { return; } journey.querySelectorAll('.projectplus-document-step[open]').forEach(function (other) { if (other !== step) { other.removeAttribute('open'); } }); }); }); }); })();</script>";
   }

